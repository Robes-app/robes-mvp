import { FEATURE_FLAGS } from '../flags';
import { PLAN_IDS, PLAN_LIMITS } from '../quotas';
import { tagDefaultRows, taxonomyRows, WEAR_SEEDS } from '../taxonomy';

export const REFERENCE_MIGRATION = '20260924000300_reference_data.sql';

function lit(value: string | null): string {
  return value === null ? 'null' : `'${value.replaceAll("'", "''")}'`;
}

function textArray(values: readonly string[]): string {
  return `array[${values.map(lit).join(', ')}]::text[]`;
}

function values(rows: string[]): string {
  return rows.map((r) => `  (${r})`).join(',\n');
}

const SCHEMA = `create table app.wardrobe_taxonomy (
  l1 text not null check (l1 in ('Tops', 'Bottoms', 'Dresses', 'Outerwear', 'Shoes', 'Bags', 'Accessories', 'Swimwear', 'Other')),
  sheet_l1 text not null,
  l2 text not null,
  l3 text not null,
  primary key (l2, l3)
);

create table app.wardrobe_tag_defaults (
  id bigint generated always as identity primary key,
  sheet_l1 text not null,
  l2 text,
  season_band text not null check (season_band in ('spring_summer', 'autumn_winter', 'year_round')),
  wear_slugs text[] not null
);
create unique index wardrobe_tag_defaults_key on app.wardrobe_tag_defaults (sheet_l1, coalesce(l2, ''));

create table app.wear_seed_labels (
  slug text primary key,
  label text not null
);

create table app.plans (
  id text primary key,
  limits jsonb not null check (jsonb_typeof(limits) = 'object'),
  updated_at timestamptz not null default now()
);
select private.track_updates('app.plans');

create table app.feature_flags (
  key text primary key,
  enabled boolean not null,
  rollout jsonb not null default '{}' check (jsonb_typeof(rollout) = 'object'),
  description text,
  updated_at timestamptz not null default now()
);
select private.track_updates('app.feature_flags');
`;

export function referenceDataSql(): string {
  const taxonomy = values(
    taxonomyRows().map((r) => [r.l1, r.sheetL1, r.l2, r.l3].map(lit).join(', ')),
  );
  const tagDefaults = values(
    tagDefaultRows().map((r) =>
      [lit(r.sheetL1), lit(r.l2), lit(r.seasonBand), textArray(r.wearSlugs)].join(', '),
    ),
  );
  const seeds = values(WEAR_SEEDS.map((s) => `${lit(s.slug)}, ${lit(s.label)}`));
  const plans = values(PLAN_IDS.map((id) => `${lit(id)}, ${lit(JSON.stringify(PLAN_LIMITS[id]))}`));
  const flags = values(
    Object.entries(FEATURE_FLAGS).map(
      ([key, f]) => `${lit(key)}, ${f.enabled}, ${lit(f.description)}`,
    ),
  );
  return `-- GENERATED by packages/core (pnpm --filter @robes/core gen:sql); edit the TS sources, never this file.
${SCHEMA}
insert into app.wardrobe_taxonomy (l1, sheet_l1, l2, l3) values
${taxonomy};

insert into app.wardrobe_tag_defaults (sheet_l1, l2, season_band, wear_slugs) values
${tagDefaults};

insert into app.wear_seed_labels (slug, label) values
${seeds};

insert into app.plans (id, limits) values
${plans};

insert into app.feature_flags (key, enabled, description) values
${flags};
`;
}
