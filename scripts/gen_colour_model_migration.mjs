#!/usr/bin/env node
// Regenerates supabase/colour_model_migration.sql (migration 27) from
// colour_model.cjs — the shade list is the one source, so the backfill's
// name → shade map is generated, never typed. Run after any edit to the
// model: `node scripts/gen_colour_model_migration.mjs`.
import { createRequire } from 'module';
import { writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';
const here = dirname(fileURLToPath(import.meta.url));
const CM = createRequire(import.meta.url)(join(here, '..', 'colour_model.cjs'));
const q = s => "'" + String(s).replace(/'/g, "''") + "'";
// Every display name and every retired wheel name → a shade id.
const pairs = [];
CM.SHADES.forEach(s => pairs.push([s.name.toLowerCase(), s.id]));
Object.keys(CM.LEGACY).forEach(k => { if (!pairs.some(p => p[0] === k)) pairs.push([k, CM.LEGACY[k]]); });
const whenLines = pairs.map(([n, id]) => `      when ${q(n)} then ${q(id)}`).join('\n');
const sql = `-- Migration 27 — the colour and pattern model (2026-10-22).
-- GENERATED by scripts/gen_colour_model_migration.mjs from colour_model.cjs.
-- Edit the model and regenerate; never this file.
--
-- Pieces record ONE shade from the shared list (74 shades in 13 families),
-- any additional shades a two- or multi-colour piece carries, and a print.
-- \`color\` survives as the display name every prompt and legacy reader
-- prints; the server writes it from the shade on every new read. The ids
-- are validated by the server against the model (no FK: the list is code,
-- like the taxonomy's fold). Idempotent; rollback at the foot.
--
-- Run once in the Supabase SQL editor. Until it runs the client strips the
-- three columns on PGRST204 (_waCmCols) and keeps filing \`color\` as before.

alter table public.wardrobe_items
  add column if not exists colour_shade text,
  add column if not exists colour_extra text[] not null default '{}',
  add column if not exists print text;

alter table public.wishlist_items
  add column if not exists colour_shade text,
  add column if not exists colour_extra text[] not null default '{}',
  add column if not exists print text;

create index if not exists idx_wardrobe_items_colour_shade on public.wardrobe_items (user_id, colour_shade) where colour_shade is not null;
create index if not exists idx_wardrobe_items_print on public.wardrobe_items (user_id, print) where print is not null;

-- Backfill: a stored colour name (a shade's display name, or one of the 21
-- retired wheel names) → its shade. Multi and Print carried no colour of
-- their own: they take print "other" and the nearest shade is left for her
-- to set (testers only — the piece sheet corrects it in one tap). A row
-- already carrying a shade is never touched.
update public.wardrobe_items
   set colour_shade = case lower(trim(color))
${whenLines}
      else colour_shade end
 where colour_shade is null and color is not null;

update public.wardrobe_items
   set print = 'other'
 where print is null and lower(trim(color)) in ('multi', 'print');

update public.wishlist_items
   set colour_shade = case lower(trim(color))
${whenLines}
      else colour_shade end
 where colour_shade is null and color is not null;

update public.wishlist_items
   set print = 'other'
 where print is null and lower(trim(color)) in ('multi', 'print');

-- Rollback (drops nothing she typed — \`color\` is untouched):
-- drop index if exists public.idx_wardrobe_items_colour_shade;
-- drop index if exists public.idx_wardrobe_items_print;
-- alter table public.wardrobe_items drop column if exists colour_shade, drop column if exists colour_extra, drop column if exists print;
-- alter table public.wishlist_items drop column if exists colour_shade, drop column if exists colour_extra, drop column if exists print;
`;
writeFileSync(join(here, '..', 'supabase', 'colour_model_migration.sql'), sql);
console.log('wrote supabase/colour_model_migration.sql —', pairs.length, 'name mappings');
